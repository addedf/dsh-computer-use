#!/usr/bin/env node
/** Prepare the native host only. Loading the extension remains an explicit
 * Chrome installation step; this script never changes browser settings.
 */
import { readFile, mkdir, writeFile, lstat, copyFile, chmod } from 'node:fs/promises'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { extensionIdFromKey, defaultChromeSocketPath, NATIVE_HOST_NAME } from '../lib/chrome-bridge.js'

const shellQuote = (value) => `'${String(value).replace(/'/g, `'"'"'`)}'`
const root = fileURLToPath(new URL('../', import.meta.url))

export async function chromeBridgeInstallPlan(options = {}) {
  const home = options.home || homedir()
  const platform = options.platform || process.platform
  if (!['darwin', 'linux'].includes(platform)) throw new Error('Chrome Native Messaging installer currently supports macOS and Linux only.')
  const dshHome = resolve(options.dshHome || process.env.DSH_HOME || join(home, '.dsh'))
  const socketPath = resolve(options.socketPath || defaultChromeSocketPath({ DSH_HOME: dshHome }))
  const manifest = JSON.parse(await readFile(join(root, 'chrome-extension/manifest.json'), 'utf8'))
  const extensionId = extensionIdFromKey(manifest.key)
  const directory = join(dshHome, 'computer-use')
  const launcher = join(directory, 'chrome-native-host')
  const nativeManifestDirectory = platform === 'darwin'
    ? join(home, 'Library/Application Support/Google/Chrome/NativeMessagingHosts')
    : join(home, '.config/google-chrome/NativeMessagingHosts')
  const nativeManifest = join(nativeManifestDirectory, `${NATIVE_HOST_NAME}.json`)
  const executable = resolve(options.nodeExecutable || process.execPath)
  const hostSource = join(root, 'tools/chrome-native-host.mjs')
  const launcherText = `#!/bin/sh\n# Generated by dsh-computer-use. No browser process is restarted.\nexport ELECTRON_RUN_AS_NODE=1\nexec ${shellQuote(executable)} ${shellQuote(hostSource)} --socket ${shellQuote(socketPath)} --extension-id ${shellQuote(extensionId)} "$@"\n`
  const nativeManifestText = JSON.stringify({ name: NATIVE_HOST_NAME, description: 'DSH Chrome Companion local bridge', path: launcher, type: 'stdio', allowed_origins: [`chrome-extension://${extensionId}/`] }, null, 2) + '\n'
  return { extensionId, extensionDirectory: join(root, 'chrome-extension'), socketPath, directory, launcher, nativeManifest, files: [{ path: launcher, content: launcherText, mode: 0o700 }, { path: nativeManifest, content: nativeManifestText, mode: 0o600 }] }
}

export async function installChromeBridge(plan) {
  // Avoid following a replaced manifest/launcher into an unrelated location.
  const backups = []
  await mkdir(plan.directory, { recursive: true, mode: 0o700 })
  const ownDirectory = await lstat(plan.directory)
  if (!ownDirectory.isDirectory() || ownDirectory.isSymbolicLink()) throw new Error('Refusing to install through a non-directory bridge path.')
  await chmod(plan.directory, 0o700)
  for (const file of plan.files) {
    const existing = await lstat(file.path).catch((cause) => { if (cause.code !== 'ENOENT') throw cause; return null })
    if (existing && (!existing.isFile() || existing.isSymbolicLink())) throw new Error('Refusing to replace a non-regular native-host file.')
    await mkdir(dirname(file.path), { recursive: true, mode: 0o700 })
    if (existing) {
      const backup = `${file.path}.backup-${Date.now()}`
      await copyFile(file.path, backup)
      backups.push(backup)
    }
    await writeFile(file.path, file.content, { mode: file.mode })
    await chmod(file.path, file.mode)
  }
  return { backups }
}

async function main() {
  const args = process.argv.slice(2)
  if (args.some((arg) => !['--install', '--dry-run'].includes(arg))) throw new Error('Usage: node tools/install-chrome-bridge.mjs [--dry-run | --install]')
  if (args.includes('--install') && args.includes('--dry-run')) throw new Error('Choose --dry-run or --install.')
  const plan = await chromeBridgeInstallPlan()
  const installed = args.includes('--install') ? await installChromeBridge(plan) : null
  console.log(JSON.stringify({ mode: installed ? 'installed' : 'dry-run', extensionId: plan.extensionId, extensionDirectory: plan.extensionDirectory, launcher: plan.launcher, nativeManifest: plan.nativeManifest, socketPath: plan.socketPath, ...(installed || {}), next: 'Load chrome-extension in Chrome after reviewing its permissions. New installations automatically connect in the background. Enable the chrome-extension backend in DSH and reload the plugin. When upgrading an older extension, enable automatic connection once in its popup. Later DSH or Chrome restarts reconnect automatically; revoking authorization disables this.' }, null, 2))
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  await main().catch((cause) => { console.error(cause.message); process.exitCode = 1 })
}
